const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {spawnSync} = require('node:child_process');
const os = require('node:os');
const M = require('../site/daily-results/model.js');
const root = path.resolve(process.argv[2] || 'public');
const day = process.argv[3] || '20261114';
const index = JSON.parse(fs.readFileSync(path.join(root, 'data', day, 'all-rider-results.json')));
const target = index.target_date;
const read = (relative, sha) => {
  const raw = fs.readFileSync(path.join(root, relative));
  if (sha) assert.equal(crypto.createHash('sha256').update(raw).digest('hex'), sha);
  return JSON.parse(raw);
};

(async () => {
  assert.equal(M.jstToday(new Date('2026-11-13T15:01:00Z')), '2026-11-14');
  assert.equal(M.jstToday(new Date('2026-11-13T14:59:00Z')), '2026-11-13');
  assert.equal(M.requestedDate(null, new Date('2026-11-14T13:00:00Z')), '2026-11-14');
  assert.equal(M.requestedDate('20261114'), target);
  assert.throws(() => M.requestedDate('20260230'));
  assert.throws(() => M.entriesFromIndex(index, '2026-11-13'));
  const entries = M.entriesFromIndex(index, target), calls = new Map();
  let active = 0, maximum = 0;
  await M.hydrate(entries, index, async (relative, sha) => {
    calls.set(relative, (calls.get(relative) || 0) + 1);
    maximum = Math.max(maximum, ++active);
    await new Promise(resolve => setTimeout(resolve, 1));
    active--; return read(relative, sha);
  });
  assert.equal(entries.length, index.summary.entries);
  assert.ok(maximum <= 5 && maximum > 1);
  assert.ok([...calls.values()].every(value => value === 1));
  assert.ok(entries.every(entry => entry.data_status.previous === 'ready' && entry.data_status.ten === 'ready'));
  const rows = [...M.resultRows(entries)];
  const previous = read(index.assets.previous.path);
  assert.equal(rows.filter(row => row.category === 'previous').length, previous.summary.results);
  assert.equal(rows.filter(row => row.category === 'ten').length, entries.reduce((n, e) => n + e.prior_ten_meetings.reduce((count, m) => count + m.days.length, 0), 0));
  const first = rows.find(row => row.race_id && row.player_id && !row.race_date_inferred), key = M.ratingKey(first.race_date, first.race_id, first.player_id);
  let requests = 0;
  const fakeClient = {from(table) {
    assert.equal(table, 'race_comments');
    const chain = {select() {return chain;}, in() {return chain;}, order() {return chain;}, range() {
      requests++;
      return {data: [{race_key: key, body: 'invalid'}, {race_key: key, body: '0'}, {race_key: key, body: '5'}]};
    }};
    return chain;
  }};
  const conditions = await M.readConditions(fakeClient, [key]);
  assert.equal(requests, 1); assert.equal(conditions.get(key), 0);
  const rated = [...M.resultRows(entries, conditions)].filter(row => row.race_id === first.race_id && row.player_id === first.player_id);
  assert.ok(rated.every(row => row.condition === 0));
  assert.ok(rows.some(row => row.start === false));
  assert.ok(rows.some(row => row.start === undefined || row.start === null));
  assert.ok(rows.some(row => row.accident));
  assert.ok(rows.some(row => row.race_id == null));
  assert.ok(rows.some(row => row.video_url?.endsWith('.mp4')));
  for (const row of rows) if (row.race_date_inferred) assert.equal(row.video_url, null);
  assert.equal(M.rankLabel({order: 0, accident: '落'}), '落');
  assert.equal(M.rankClass({race_type: 'S級準々決勝'}), '');
  assert.equal(M.rankClass({race_type: 'S級準決勝'}), 'rank-semifinal');
  assert.equal(M.rankClass({race_type: 'S級決勝'}), 'rank-important');
  const sample = {order: 3, player_id: '000001', race_id: '012820261001', race_number: 1, race_date: '2026-10-01', video_url: 'https://keirin.kdreams.jp/stadium/digest/?kyogijoCd=28&kaisaiDate=20261001&gradeCd=3&raceNo=1'};
  assert.match(M.replayUrl(sample, '000001', '28'), /20261001-28-03-01-01-00\.mp4$/);
  assert.equal(M.replayUrl({...sample, race_date_inferred: true}, '000001', '28'), null);
  assert.equal(M.replayUrl(sample, '000002', '28'), null);
  const csv = M.csv(M.RESULT_COLUMNS, M.resultRows(entries, conditions));
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'daily-results-csv-'));
  fs.writeFileSync(path.join(temporary, 'results.csv'), csv);
  const parsed = spawnSync('python3', ['-c', 'import sys,csv,json; rows=list(csv.DictReader(open(sys.argv[1],encoding="utf-8-sig",newline=""))); print(json.dumps({"count":len(rows),"ids":[r["player_id"] for r in rows[:3]],"zero":sum(r["condition"]=="0" for r in rows),"false":sum(r["start"]=="0" for r in rows),"unknown":sum(r["start"]=="" for r in rows)}))', path.join(temporary, 'results.csv')], {encoding: 'utf8', timeout: 10000});
  assert.equal(parsed.status, 0, parsed.stderr);
  const receipt = JSON.parse(parsed.stdout);
  assert.equal(receipt.count, rows.length); assert.ok(receipt.ids.every(id => /^\d{6}$/.test(id)));
  assert.ok(receipt.zero && receipt.false && receipt.unknown);
  assert.equal(M.csv(['name', 'time'], [{name: '名前,"改行\n', time: '9.70'}]), '\uFEFF"name","time"\r\n"名前,""改行\n","9.70"\r\n');
  const broken = M.entriesFromIndex(index, target);
  await M.hydrate(broken, index, async (relative, sha) => {
    if (relative === index.assets.previous.path || relative === entries[0].history_ref.path) throw new Error('Unavailable');
    return read(relative, sha);
  });
  assert.equal(broken.length, entries.length);
  assert.ok(broken.every(e => e.data_status.previous === 'error'));
  assert.equal(broken[0].data_status.ten, 'error');
  assert.ok(broken.slice(1).every(e => e.data_status.ten === 'ready'));
  await M.hydrate(entries, index, async () => {throw new Error('Later failure');});
  assert.ok(entries.every(e => e.previous_meetings.length && e.prior_ten_meetings.length));
  assert.ok(entries.every(e => e.data_status.previous === 'stale' && e.data_status.ten === 'stale'));
  console.log('DAILY RESULTS PASS', entries.length, 'entries', rows.length, 'category results; complete CSV, identities, partial failures and zero clear verified');
})().catch(error => {console.error(error); process.exitCode = 1;});
